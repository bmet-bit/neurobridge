"""Generate a deterministic, explicitly synthetic lab bundle."""

from __future__ import annotations

import csv
from collections.abc import Iterable
from pathlib import Path

import h5py
import numpy as np

from .session import Session

FIXTURE_RATE = 1000.0
FIXTURE_SCALE = 1.000175
FIXTURE_OFFSET = -0.125
FIXTURE_START = 0.25


def write_csv(path: Path, header: tuple[str, ...], rows: Iterable[tuple]) -> None:
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(header)
        writer.writerows(rows)


def make_fixture(directory: Path, *, frames: int = 20_000, channels: int = 8) -> Path:
    """Generate HDF5 in blocks and give behavior a known drift, outlier and missing pairs."""
    if frames < 2_000 or channels < 1 or channels > 256:
        raise ValueError("Synthetic fixture needs at least 2,000 frames and 1–256 channels")
    directory.mkdir(parents=True, exist_ok=False)
    try:
        return _write_fixture(directory, frames, channels)
    except BaseException:
        # The exclusive mkdir above establishes ownership of these output paths.
        for path in directory.iterdir():
            path.unlink()
        directory.rmdir()
        raise


def _write_fixture(directory: Path, frames: int, channels: int) -> Path:
    recording = directory / "synthetic-voltage.h5"
    with h5py.File(recording, "x") as file:
        file.attrs["format"] = "neurobridge-lab-v1"
        chunk_frames = min(4096, frames)
        data = file.create_dataset(
            "voltage", shape=(frames, channels), dtype="int16", chunks=(chunk_frames, channels)
        )
        data.attrs.update(unit="uV", rate_hz=FIXTURE_RATE, start_s=FIXTURE_START)
        file.create_dataset(
            "channel_labels",
            data=[f"SYN{i:03d}" for i in range(channels)],
            dtype=h5py.string_dtype("utf-8"),
        )
        rng = np.random.default_rng(75419)
        for start in range(0, frames, chunk_frames):
            length = min(frames - start, chunk_frames)
            data[start : start + length] = rng.integers(
                -512, 513, size=(length, channels), dtype=np.int16
            )

    duration = frames / FIXTURE_RATE
    pulse_times = FIXTURE_START + np.linspace(0.05, 0.95, 9) * duration
    ids = [f"pulse-{i:02d}" for i in range(len(pulse_times))]
    behavior_pulses = (pulse_times - FIXTURE_OFFSET) / FIXTURE_SCALE
    neural_pulses = pulse_times.copy()
    neural_pulses[4] += 0.050
    write_csv(
        directory / "synthetic-behavior-pulses.csv",
        ("pulse_id", "time_s"),
        [("behavior-only", 0.0), *zip(ids, behavior_pulses, strict=True)],
    )
    write_csv(
        directory / "synthetic-neural-pulses.csv",
        ("pulse_id", "time_s"),
        [*zip(ids, neural_pulses, strict=True), ("neural-only", FIXTURE_START + 0.99 * duration)],
    )
    phase = np.linspace(0, 2 * np.pi, 60)
    positions_s = FIXTURE_START + np.linspace(0.1, 0.9, len(phase)) * duration
    positions_s += 0.003 * np.sin(7 * phase)
    write_csv(
        directory / "synthetic-position.csv",
        ("time_s", "x_m", "y_m"),
        zip(
            (positions_s - FIXTURE_OFFSET) / FIXTURE_SCALE,
            0.2 * np.cos(phase),
            0.2 * np.sin(phase),
            strict=True,
        ),
    )

    manifest = directory / "session.json"
    session = Session(
        format="lab-hdf5",
        recording=Path(recording.name),
        behavior=Path("synthetic-position.csv"),
        behavior_pulses=Path("synthetic-behavior-pulses.csv"),
        neural_pulses=Path("synthetic-neural-pulses.csv"),
        session_id="synthetic-lab",
        subject_id="fixture",
        species="Mus musculus",
        sex="U",
        age="P90D",
        start_time="2025-01-01T00:00:00Z",
        description="Synthetic voltage and planar motion with controlled clock drift",
        device="Synthetic amplifier",
        location="VISp",
        source="Generated by NeuroBridge with RNG seed 75419",
        license="CC0-1.0",
        time_reference="Synthetic UTC session origin. Neural samples begin at 0.25 seconds.",
        synthetic=True,
    )
    manifest.write_text(session.model_dump_json(indent=2) + "\n", encoding="utf-8")
    return manifest
