def test_heterogeneous_edf_roundtrip(edf_session: Session, tmp_path: Path) -> None:
    path = tmp_path / "calibrated.nwb"
    convert(edf_session, path, buffer_frames=11)
    result = validate(edf_session, path)
    assert result.passed, result.to_dict()
    with NWBHDF5IO(path, "r") as io:
        series = io.read().acquisition["NeuralVoltage"]
        np.testing.assert_allclose(
            series.get_data_in_units()[:3, 0], [-1e-4, 5e-5, 2e-4], atol=1e-12
        )
        assert series.data.chunks == (11, 2)
    with pytest.raises(FileExistsError):
        convert(edf_session, path)


@pytest.mark.parametrize(
    ("dataset", "index", "value", "check"),
    [
        (DATA, (20, 0), 700, "physical values"),
        (DATA, (20, 0), float("nan"), "physical values"),
        ("/acquisition/NeuralVoltage/electrodes", 0, 1, "electrode order"),
        ("/intervals/task_annotations/stop_time", 0, 0.7, "task annotations"),
    ],
)
def test_schema_valid_corruption(
    edf_session: Session, tmp_path: Path, dataset: str, index: tuple | int, value: float, check: str
) -> None:
    path = tmp_path / "corrupt.nwb"
    convert(edf_session, path)
    with h5py.File(path, "r+") as file:
        file[dataset][index] = value
    result = validate(edf_session, path)
    assert result.schema_errors == []
    assert not result.passed
    assert any(item.check == check and not item.passed for item in result.science)


def test_schema_failure_is_reported(edf_session: Session, tmp_path: Path) -> None:
    path = tmp_path / "missing-field.nwb"
    convert(edf_session, path)
    with h5py.File(path, "r+") as file:
        del file["session_description"]
    result = validate(edf_session, path)
    assert result.schema_errors
    assert not result.passed


@pytest.mark.real
def test_physionet_cli(tmp_path: Path) -> None:
    cache = os.environ.get("NEUROBRIDGE_REAL_EDF")
    if cache is None:
        pytest.skip("Set NEUROBRIDGE_REAL_EDF to the pinned demo EDF+ file")
    shutil.copyfile(cache, tmp_path / "S001R03.edf")
    manifest = fetch_demo(tmp_path)
    output = tmp_path / "demo.nwb"
    report = tmp_path / "demo.html"
    assert main(["inspect", str(manifest)]) == 0
    assert main(["convert", str(manifest), str(output)]) == 0
    assert main(["validate", str(manifest), str(output)]) == 1
    assert (
        main(["validate", str(manifest), str(output), "--allow-missing-age", "--html", str(report)])
        == 0
    )
    assert "1,280,000 values" in report.read_text(encoding="utf-8")
    assert "30 / 30 intervals" in report.read_text(encoding="utf-8")
    result = validate(load_session(manifest), output, allow_missing_age=True)
    assert next(item for item in result.science if item.check == "physical values").passed
    with h5py.File(output, "r+") as file:
        file["/acquisition/NeuralVoltage/starting_time"].attrs["rate"] = 161.0
    result = validate(load_session(manifest), output, allow_missing_age=True)
    assert not result.schema_errors
    assert any(item.check == "sample clock" and not item.passed for item in result.science)
